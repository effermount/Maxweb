'use strict';
const {app,session,Notification}=require('electron');
const fs=require('node:fs'),os=require('node:os'),path=require('node:path'),assert=require('node:assert/strict');
const profile=fs.mkdtempSync(path.join(os.tmpdir(),'maxweb-mute-'));
app.setPath('userData',profile);
Notification.prototype.show=function(){this.emit('show');};
Notification.prototype.close=function(){this.emit('close');};
const fixture=()=>new Response('<html><body>Account notification fixture</body></html>',{headers:{'content-type':'text/html'}});
app.whenReady().then(()=>session.fromPartition('persist:max').protocol.handle('https',fixture));
const client=require('../src/main.cjs');
const deadline=setTimeout(()=>app.exit(1),20000);
const loaded=async c=>{if(c.isLoading())await new Promise(r=>c.once('did-stop-loading',r));};
const wait=async check=>{for(let i=0;i<50;i++){if(await check())return;await new Promise(r=>setTimeout(r,40));}throw Error('Timed out');};
client.ready.then(async()=>{
 const shell=client.getMainWindow().webContents;await loaded(shell);
 const secondID=client.addAccount('Second').activeAccountId;
 client.getSession(secondID).protocol.handle('https',fixture);await client.loadMax(secondID);
 const first=client.getAccountContents('default'),second=client.getAccountContents(secondID);
 await Promise.all([loaded(first),loaded(second)]);
 const js=code=>shell.executeJavaScript(code);
 const send=c=>c.executeJavaScript('new Notification("Fixture",{body:"Test"});void 0');
 await send(first);await wait(()=>client.getAccountNotifications().size===1);
 await js('window.maxwebShell.collapse(true)');
 await js('document.querySelector(".account-mute").click()');
 await wait(()=>client.getState().accounts[0].notifications===false);
 assert.equal(client.getAccountNotifications().size,0,'Existing banner must close');
 assert.equal(client.getState().activeAccountId,secondID,'Toggle must not switch account');
 await send(first);await new Promise(r=>setTimeout(r,80));assert.equal(client.getAccountNotifications().size,0);
 await send(second);await wait(()=>client.getAccountNotifications().size===1);
 assert.equal(require('../src/store.cjs').createStore(profile).get().accounts[0].notifications,false,'Mute must survive reopening preferences');
 await js('document.querySelector(".account-mute").click()');
 await wait(()=>client.getState().accounts[0].notifications===true);
 await send(first);await wait(()=>client.getAccountNotifications().size===2);
 await js('window.maxwebShell.collapse(false)');
 await wait(()=>js('document.querySelectorAll(".account-mute").length===2'));
 assert.equal(await js('document.querySelector(".account-mute").getAttribute("aria-pressed")'),'false');
 await assert.rejects(js('window.maxwebShell.notifications("missing",false)'));
 console.log('PASS: account mute from compact sidebar, no account switch, existing banner closure, other account unaffected, persistence and re-enable');
 clearTimeout(deadline);app.quit();
}).catch(e=>{console.error(e);app.exit(1);});
app.on('will-quit',()=>fs.rmSync(profile,{recursive:true,force:true}));
