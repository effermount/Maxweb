'use strict';
const { app, session, BrowserWindow } = require('electron');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const assert = require('node:assert/strict');
const { once } = require('node:events');
const data = process.env.MAXWEB_TEST_PROFILE || fs.mkdtempSync(path.join(os.tmpdir(), 'maxweb-runtime-'));
app.setPath('userData', data);
const client = require('../src/main.cjs');
const deadline = setTimeout(() => { console.error('FAIL: runtime test timed out'); app.exit(1); }, 90000);
async function loaded(contents) { if (contents.isLoading()) await once(contents, 'did-stop-loading'); }
async function waitFor(check, message) {
  const start = Date.now();
  while (Date.now() - start < 35000) { if (await check()) return; await new Promise(resolve => setTimeout(resolve, 100)); }
  throw new Error(message);
}
async function hydrated(contents) { await loaded(contents); await waitFor(() => contents.executeJavaScript('document.body.innerText.trim().length > 20'), 'MAX did not render its login page'); }
client.ready.then(async () => {
  const win = client.getMainWindow();
  const primary = client.getAccountContents('default');
  await hydrated(primary);
  for (const [key, expected] of [['sandbox', true], ['nodeIntegration', false], ['contextIsolation', true]]) assert.equal(primary.getLastWebPreferences()[key], expected);
  assert.equal(primary.getBackgroundThrottling(), false);
  for (const variable of ['require', 'maxweb', 'maxwebShell']) assert.equal(await primary.executeJavaScript(`typeof window.${variable}`), 'undefined');
  assert.ok(primary.getURL().startsWith('https://web.max.ru/'));
  assert.equal(await primary.executeJavaScript('Notification.permission'), 'granted');
  assert.equal(client.getSession('default'), session.fromPartition('persist:max'));
  console.log('PASS: v1.0 profile retained, official MAX isolated from native APIs');
  await client.getSession('default').cookies.set({ url: 'https://web.max.ru/', name: 'maxweb-smoke', value: 'primary', expirationDate: Date.now() / 1000 + 3600, secure: true });
  await primary.executeJavaScript('localStorage.setItem("maxweb-smoke", "primary")');
  const state = client.addAccount('Рабочий');
  const secondID = state.activeAccountId;
  const second = client.getAccountContents(secondID);
  await hydrated(second);
  assert.equal((await client.getSession(secondID).cookies.get({ name: 'maxweb-smoke' })).length, 0);
  assert.equal(await second.executeJavaScript('localStorage.getItem("maxweb-smoke")'), null);
  await client.getSession(secondID).cookies.set({ url: 'https://web.max.ru/', name: 'maxweb-smoke', value: 'secondary', expirationDate: Date.now() / 1000 + 3600, secure: true });
  await second.executeJavaScript('localStorage.setItem("maxweb-smoke", "secondary")');
  client.renameAccount(secondID, 'Личный');
  client.selectAccount('default');
  assert.equal(client.getAccountContents(), primary);
  assert.equal(await primary.executeJavaScript('localStorage.getItem("maxweb-smoke")'), 'primary');
  assert.equal((await client.getSession('default').cookies.get({ name: 'maxweb-smoke' }))[0].value, 'primary');
  assert.equal(BrowserWindow.getAllWindows().length, 1);
  assert.equal(second.getBackgroundThrottling(), false);
  console.log('PASS: two accounts switch inside one window without reloading or sharing cookies/localStorage');
  win.close();
  assert.equal(win.isDestroyed(), false); assert.equal(win.isVisible(), false);
  assert.equal(await primary.executeJavaScript('1+1'), 2);
  assert.equal(await second.executeJavaScript('1+1'), 2);
  client.showWindow(); assert.equal(win.isVisible(), true);
  console.log('PASS: all account renderers remain alive after closing the window');
  const settings = client.showSettings();
  await loaded(settings.webContents);
  assert.equal(BrowserWindow.getAllWindows().length, 1);
  const config = await settings.webContents.executeJavaScript('window.maxweb.get()');
  assert.equal(config.notifications, true); assert.equal(config.arch, 'arm64'); assert.equal(config.version, '1.1.0');
  await settings.webContents.executeJavaScript('window.maxweb.notifications(false)');
  await Promise.all([loaded(primary), loaded(second)]);
  assert.equal(await primary.executeJavaScript('Notification.permission'), 'denied');
  assert.equal(await second.executeJavaScript('Notification.permission'), 'denied');
  await settings.webContents.executeJavaScript('window.maxweb.notifications(true)');
  await Promise.all([loaded(primary), loaded(second)]);
  assert.equal(await primary.executeJavaScript('Notification.permission'), 'granted');
  assert.equal(await second.executeJavaScript('Notification.permission'), 'granted');
  console.log('PASS: settings and notification permissions apply to every account');
  await settings.webContents.executeJavaScript('window.maxweb.updateConfigure("example/Maxweb", false)');
  assert.equal((await settings.webContents.executeJavaScript('window.maxweb.get()')).updates.repository, 'example/Maxweb');
  await assert.rejects(settings.webContents.executeJavaScript('window.maxweb.updateConfigure("https://evil.test/x", true)'));
  console.log('PASS: update configuration validates GitHub origin and persists preferences');
  assert.equal(await settings.webContents.executeJavaScript('document.documentElement.scrollWidth <= innerWidth'), true);
  const qa = path.join(__dirname, '../.tools/qa'); fs.mkdirSync(qa, { recursive: true });
  fs.writeFileSync(path.join(qa, 'settings-1.1.png'), (await settings.webContents.capturePage()).toPNG());
  client.selectAccount('default');
  await Promise.all([hydrated(primary), hydrated(second)]);
  await primary.executeJavaScript('document.title = "3 непрочитанных чата"');
  await second.executeJavaScript('document.title = "7 непрочитанных чатов"');
  await waitFor(() => app.dock.getBadge() === '10', 'Unread totals did not update');
  console.log('PASS: unread counters aggregate across account sessions');
  await second.executeJavaScript('const testNotification = new Notification("Maxweb runtime test"); testNotification.dispatchEvent(new Event("click")); testNotification.close();', true);
  await waitFor(() => client.getState().activeAccountId === secondID, 'Notification click did not switch to the correct account');
  console.log('PASS: notification click routes to its own account while preserving native Notification API');
  client.selectAccount('default');
  primary.debugger.attach('1.3');
  await primary.debugger.sendCommand('Network.enable');
  await primary.debugger.sendCommand('Network.setBypassServiceWorker', { bypass: true });
  await primary.debugger.sendCommand('Network.setCacheDisabled', { cacheDisabled: true });
  const fail = (_event, method, params) => { if (method === 'Fetch.requestPaused') void primary.debugger.sendCommand('Fetch.failRequest', { requestId: params.requestId, errorReason: 'InternetDisconnected' }); };
  primary.debugger.on('message', fail);
  await primary.debugger.sendCommand('Fetch.enable', { patterns: [{ urlPattern: 'https://web.max.ru/*', resourceType: 'Document', requestStage: 'Request' }] });
  win.hide(); await client.loadMax('default');
  await waitFor(() => primary.getURL().endsWith('/ui/offline.html'), 'Offline page did not appear');
  assert.equal(win.isVisible(), false);
  assert.equal(await second.executeJavaScript('localStorage.getItem("maxweb-smoke")'), 'secondary');
  await primary.debugger.sendCommand('Fetch.disable'); primary.debugger.removeListener('message', fail);
  await client.loadMax('default'); await hydrated(primary); primary.debugger.detach();
  console.log('PASS: per-account offline recovery preserves other sessions and keeps window hidden');
  client.selectAccount(secondID);
  await client.flushSessions();
  fs.writeFileSync(path.join(data, 'test-expectations.json'), JSON.stringify({ secondID }));
  clearTimeout(deadline); console.log('ALL RUNTIME CHECKS PASSED'); app.quit();
}).catch(error => { console.error(error); clearTimeout(deadline); app.exit(1); });
