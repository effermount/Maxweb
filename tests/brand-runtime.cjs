'use strict';
const { app, session, Menu, nativeImage, nativeTheme } = require('electron');
const fs = require('node:fs'), os = require('node:os'), path = require('node:path'), assert = require('node:assert/strict');
const profile = fs.mkdtempSync(path.join(os.tmpdir(), 'obla-brand-'));
app.setPath('userData', profile);
require('../src/store.cjs').createStore(profile).set({ theme: 'dark', accounts: [{ id: 'default', name: 'Личный аккаунт', customName: true }] });
app.on('session-created', ses => ses.protocol.handle('https', () => new Response('<html><title>Messenger fixture</title><body>Test account</body></html>', { headers: { 'content-type': 'text/html' } })));
const client = require('../src/main.cjs');
const deadline = setTimeout(() => app.exit(1), 20000);
const wait = async (check, label) => { for (let n = 0; n < 150; n++) { if (await check()) return; await new Promise(r => setTimeout(r, 30)); } throw Error('Timed out: '+label); };
client.ready.then(async () => {
  assert.equal(app.getName(), 'Maxweb', 'Internal encryption namespace remains unchanged');
  assert.equal(app.getPath('userData'), profile);
  assert.equal(client.getState().accounts[0].name, 'Личный аккаунт', 'Existing profile remains loaded');
  assert.equal(client.getSession('default'), session.fromPartition('persist:max'), 'Original account session is unchanged');
  assert.equal(Menu.getApplicationMenu().items[0].label, 'Обла');
  const shell = client.getMainWindow().webContents;
  await wait(() => !shell.isLoading(), 'shell');
  const js = code => shell.executeJavaScript(code);
  assert.equal(await js('document.querySelector(".brand h1").textContent'), 'Обла');
  assert.equal(await js('document.querySelector(".brand-mark path").getAttribute("d").startsWith("M592")'), true);
  const qa = path.join(__dirname, '../.tools/qa'); fs.mkdirSync(qa, { recursive: true });
  client.addAccount('Рабочий аккаунт', 'telegram'); client.addAccount('Семья', 'whatsapp');
  await js('new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)))');
  fs.writeFileSync(path.join(qa, 'obla-sidebar-dark.png'), (await shell.capturePage({ x: 0, y: 0, width: 220, height: 680 })).toPNG());
  const settings = client.showSettings().webContents;
  await wait(() => !settings.isLoading(), 'settings');
  await wait(() => settings.executeJavaScript('document.getElementById("version").textContent.startsWith("Обла ")'), 'settings brand');
  assert.match(await settings.executeJavaScript('document.querySelector("header h1").textContent'), /^Обла/);
  await wait(() => settings.executeJavaScript('document.querySelector("header img").complete'), 'icon');
  assert.equal(await settings.executeJavaScript('document.getElementById("repository").value'), 'effermount/Maxweb');
  await settings.executeJavaScript('new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r)))');
  fs.writeFileSync(path.join(qa, 'obla-settings-dark.png'), (await settings.capturePage()).toPNG());
  // Render the lock surface using a fixture state; no real biometric prompt or keychain access.
  shell.send('shell:state', { ...client.getState(), locked: true, security: { enabled: true, touchIDAvailable: false, touchID: false } });
  await wait(() => js('!document.getElementById("lock-screen").hidden'), 'lock brand');
  assert.equal(await js('document.getElementById("lock-title").textContent'), 'Разблокировать «Обла»');
  fs.writeFileSync(path.join(qa, 'obla-lock-dark.png'), (await shell.capturePage()).toPNG());
  nativeTheme.themeSource = 'light';
  await js('new Promise(r=>setTimeout(r,150))');
  fs.writeFileSync(path.join(qa, 'obla-lock-light.png'), (await shell.capturePage()).toPNG());
  for (const file of ['icon.png', 'trayTemplate.png', 'trayTemplate@2x.png']) assert(!nativeImage.createFromPath(path.join(__dirname, '../assets', file)).isEmpty());
  fs.writeFileSync(path.join(qa, 'obla-icon.png'), nativeImage.createFromPath(path.join(__dirname, '../assets/icon.png')).resize({ width: 256 }).toPNG());
  console.log('PASS: Obla UI/menu/icons, original profile/session retained, dark/light lock and settings previews');
  clearTimeout(deadline); setTimeout(() => app.exit(0), 2000).unref(); app.quit();
}).catch(error => { console.error(error); app.exit(1); });
app.on('will-quit', () => fs.rmSync(profile, { recursive: true, force: true }));
